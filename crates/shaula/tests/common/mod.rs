/// Recomputes the store-issued bindings commitment for a profile revision.
pub fn expected_bindings_digest(profile_key: &str, revision: i64) -> String {
    use hmac::Mac;
    let mut mac = hmac::Hmac::<sha2::Sha256>::new_from_slice(b"test-bindings-key").unwrap();
    mac.update(b"shaula.bindings_digest.v1");
    mac.update(format!("{profile_key}/{revision}").as_bytes());
    format!("bd1_{}", hex::encode(mac.finalize().into_bytes()))
}

pub fn put_with_idempotency(uri: &str, idem: &str, body: String) -> Request<Body> {
    let mut request = authorized("PUT", uri, Some(body));
    request
        .headers_mut()
        .insert("if-none-match", axum::http::HeaderValue::from_static("*"));
    request.headers_mut().insert(
        "idempotency-key",
        axum::http::HeaderValue::from_str(idem).unwrap(),
    );
    request
}

pub async fn get_json(app: &axum::Router, uri: &str) -> serde_json::Value {
    let response = app
        .clone()
        .oneshot(authorized("GET", uri, None))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK, "GET {uri} must succeed");
    let body = axum::body::to_bytes(response.into_body(), 1 << 20)
        .await
        .unwrap();
    serde_json::from_slice(&body).unwrap()
}

/// Builds the full attestation body by recomputing every authority
/// member from the store: the lock digest, the provider set parsed from
/// the artifact's lock file, the engine binary digest of THE configured
/// engine, the admitted manifest's engine/images/policy, and the
/// bindings commitment via HMAC.
pub async fn attest_body(
    control_plane: &Arc<SqliteControlPlane>,
    artifact_digest: &str,
    bindings_digest: &str,
    engine_binary: &std::path::Path,
) -> String {
    let lock = control_plane
        .artifact_lock_digest(artifact_digest)
        .await
        .unwrap()
        .unwrap_or_default();
    // The manifest is the authority: the subject copies IT, never
    // invented values (a forged member must fail activation).
    let manifest_text = control_plane
        .artifact_manifest(artifact_digest)
        .await
        .unwrap()
        .unwrap_or_default();
    let manifest: shaula_core::template::ProfileManifest =
        serde_yaml::from_str(&manifest_text).unwrap();
    let images: Vec<String> = manifest
        .runner_image_digests
        .iter()
        .map(|i| format!("\"{i}\""))
        .collect();
    let images = images.join(", ");
    // Provider set recomputed from the SAME lock file the store holds.
    let lock_text = control_plane
        .artifact_lock_file(artifact_digest)
        .await
        .unwrap()
        .unwrap_or_default();
    let providers: Vec<String> = shaula_core::lockfile::parse_lock_providers(&lock_text)
        .unwrap()
        .iter()
        .map(|p| {
            format!(
                r#"{{"source": "{}", "version": "{}", "checksums_digest": "{}"}}"#,
                shaula_core::lockfile::provider_source(&p.source),
                p.version,
                p.checksums_digest
            )
        })
        .collect();
    let providers = providers.join(", ");
    let engine_binary_digest = {
        use sha2::Digest;
        let bytes = std::fs::read(engine_binary).unwrap();
        format!("sha256:{}", hex::encode(sha2::Sha256::digest(&bytes)))
    };
    format!(
        r#"{{
        "result": "passed",
        "subject": {{
            "artifact_digest": "{artifact_digest}",
            "dependency_lock_digest": "{lock}",
            "providers": [{providers}],
            "bindings_digest": "{bindings_digest}",
            "platform": "{platform}",
            "bindings_contract": "{contract}",
            "engine": {{"kind": "{engine_kind}", "required_version": "{engine_version}", "version": "1.9.8", "binary_digest": "{engine_binary_digest}"}},
            "runner_image_digests": [{images}],
            "runtime_policy_digest": "{policy}",
            "suite": {{"name": "shaula-template-conformance", "version": "v1"}}
        }},
        "suite": {{"name": "shaula-template-conformance", "version": "v1"}},
        "completed_at": 1800000000
    }}"#,
        platform = manifest.platform,
        contract = manifest.bindings_contract,
        engine_kind = manifest.runtime.engine,
        engine_version = manifest.runtime.required_version,
        policy = manifest.runtime_policy_digest,
    )
}


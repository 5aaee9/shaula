/// A stand-in engine binary: attestation subjects are hashed against
/// THIS file, and a forged binary digest must fail.
pub fn fixture_engine(dir: &std::path::Path) -> std::path::PathBuf {
    std::fs::create_dir_all(dir).unwrap();
    let path = dir.join("terraform.cmd");
    std::fs::write(&path, "@echo off\r\nexit /b 0\r\n").unwrap();
    path
}

/// Assembles the router plus the store handle used to drive scans.
/// Returns the engine binary path too: it is the subject's
/// binary-digest authority (attest_body hashes the same file).
pub async fn build_app_with_scan() -> (axum::Router, Arc<SqliteControlPlane>, std::path::PathBuf) {
    let (app, control_plane, engine, _service) = build_app_with_service().await;
    (app, control_plane, engine)
}

/// Like [`build_app_with_scan`], but also returns the artifact root —
/// for tests that must manipulate the published artifact files in place
/// (e.g. the R7-03 unreadable-authority semantics).
pub async fn build_app_with_artifact_root() -> (
    axum::Router,
    Arc<SqliteControlPlane>,
    std::path::PathBuf,
    std::path::PathBuf,
) {
    let (app, control_plane, engine, _service, artifact_root) = build_app_inner().await;
    (app, control_plane, engine, artifact_root)
}

/// Assembles the router, the store handle and the service.
pub async fn build_app_with_service() -> (
    axum::Router,
    Arc<SqliteControlPlane>,
    std::path::PathBuf,
    Arc<ControlPlane>,
) {
    let (app, control_plane, engine, service, _artifact_root) = build_app_inner().await;
    (app, control_plane, engine, service)
}

async fn build_app_inner() -> (
    axum::Router,
    Arc<SqliteControlPlane>,
    std::path::PathBuf,
    Arc<ControlPlane>,
    std::path::PathBuf,
) {
    // R7-06: engine spawns run behind the fence supervisor, whose hidden
    // marker only the real `shaula` binary routes — point the supervisor
    // at it (a test-harness binary cannot route the marker itself).
    std::env::set_var("SHAULA_ENGINE_FENCE_EXE", env!("CARGO_BIN_EXE_shaula"));
    let tmp = tempfile::tempdir().unwrap();
    let artifact_root = tmp.path().join("artifacts");
    let data_dir = tmp.path().join("data");
    std::fs::create_dir_all(&artifact_root).unwrap();
    std::fs::create_dir_all(&data_dir).unwrap();
    let tmp_path = tmp.path().to_path_buf();
    std::mem::forget(tmp);

    let store = Store::open(&data_dir.join("test.db")).await.unwrap();
    store.migrate().await.unwrap();
    let control_plane = Arc::new(SqliteControlPlane::new(store, artifact_root.clone()));

    let engine_binary = fixture_engine(&tmp_path.join("engine"));
    let service = Arc::new(ControlPlane::new(
        control_plane.clone(),
        fixed_clock(),
        b"test-bindings-key".to_vec(),
        100,
        engine_binary.clone(),
    ));
    service.set_ready(true);
    let service_for_return = Arc::clone(&service);

    let router = shaula_http::router::build_router(shaula_http::router::AppState {
        fleets: service.clone(),
        profiles: service.clone(),
        health: service,
        oidc: oidc::oidc().await,
        body_limit: 64 * 1024 * 1024,
        request_body_limit: 64 * 1024 * 1024,
        artifact_publisher: Arc::new(TestPublisher {
            root: artifact_root.clone(),
        }),
    });
    (
        router,
        control_plane,
        engine_binary,
        service_for_return,
        artifact_root,
    )
}

pub fn fixture_artifact() -> (String, Vec<u8>) {
    let mut builder = tar::Builder::new(Vec::new());
    for (name, content) in [
        (
            "profile.yaml",
            "api_version: shaula.io/template-profile/v1\nkind: RunnerTemplateProfile\nplatform: kubernetes\nruntime:\n  protocol: terraform-cli/v1\n  engine: terraform\n  root_module: .\n  required_version: \">= 1.9, < 2.0\"\nbindings_contract: shaula.bindings.kubernetes/v1\nschemas:\n  bindings: schemas/bindings.schema.json\n  parameters: schemas/parameters.schema.json\nmanaged_resource_shape:\n  - role: bootstrap\n    terraform_type: kubernetes_secret_v1\n    exact_count: 1\n  - role: runner\n    terraform_type: kubernetes_pod_v1\n    exact_count: 1\nrunner_image_digests:\n  - ghcr.io/actions/actions-runner:2.323.0@sha256:3f2a1b9c4d5e6f708192a3b4c5d6e7f8091a2b3c4d5e6f708192a3b4c5d6e7f8\nruntime_policy_digest: sha256:policy-v1\n",
        ),
        (".terraform.lock.hcl", FIXTURE_LOCK_HCL),
        ("schemas/bindings.schema.json", "{}"),
        ("schemas/parameters.schema.json", "{}"),
        ("main.tf", "resource \"kubernetes_secret_v1\" \"bootstrap\" {}\n"),
    ] {
        let mut header = tar::Header::new_gnu();
        header.set_size(content.len() as u64);
        header.set_mode(0o644);
        header.set_cksum();
        builder
            .append_data(&mut header, name, content.as_bytes())
            .unwrap();
    }
    let tar_bytes = builder.into_inner().unwrap();
    let mut encoder = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::fast());
    std::io::Write::write_all(&mut encoder, &tar_bytes).unwrap();
    let bytes = encoder.finish().unwrap();
    let digest = {
        use sha2::Digest;
        let mut hasher = sha2::Sha256::new();
        hasher.update(&bytes);
        format!("sha256:{}", hex::encode(hasher.finalize()))
    };
    (digest, bytes)
}

pub fn authorized(method: &str, uri: &str, body: Option<String>) -> Request<Body> {
    let mut builder = Request::builder()
        .method(method)
        .uri(uri)
        .header("authorization", crate::common::oidc::bearer("fleet.read fleet.write fleet.retire template.read template.publish template.attest template.retire auth.read auth.write auth.retire"));
    // R10-05: conditional writes are mandatory — test PUTs are all
    // create-style re-assertions, so they carry If-None-Match: *.
    if method == "PUT" {
        builder = builder.header("if-none-match", "*");
    }
    match body {
        Some(body) => builder.body(Body::from(body)).unwrap(),
        None => builder.body(Body::empty()).unwrap(),
    }
}

